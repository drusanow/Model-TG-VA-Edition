#!/usr/bin/env python3
"""Writes src/sfx_tables.inc: the tables of the alternative send effects
(src/sendfx.inc, docs/SENDFX.md). Rerun after changing a curve; the tests
check that the file is up to date.

  sfx_rate  by a dial's value 0..127 (the FX parameter >> 8): an LFO's
            speed, 0.05 Hz .. 10 Hz (exponential), as the step of a 32-bit
            phase per 32-sample block at 48 kHz. sendfx.inc also reads it
            x 12.5 as the ring modulator's carrier step a sample (20 Hz ..
            4 kHz), and >> 13 as the distortion's drive (Q4, x1.06 .. x218)
  sfx_apc   by the phaser's sweep position 0..64: a first-order allpass
            coefficient, Q14, for a break frequency of
            100 Hz .. 4 kHz (exponential): a = (t - 1) / (t + 1),
            t = tan(pi f / 48000), so y = x1 + a (x - y1)
"""
import math
import os

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..',
                   'src', 'sfx_tables.inc')
FS = 48000

rate = [round(0.05 * 200 ** (i / 127) * 32 / FS * 2 ** 32) for i in range(128)]


def apc(j):
    t = math.tan(math.pi * 100 * 40 ** (j / 64) / FS)
    return round(16384 * (t - 1) / (t + 1))


ap = [apc(j) for j in range(65)]
assert all(a < b for a, b in zip(rate, rate[1:])), "the curve must rise"
assert rate[-1] * 25 < 2 ** 31 and rate[0] >> 13 >= 16
assert all(-16384 < a < 0 for a in ap)


def rows(name, vals, kind):
    L = [f"{name}:"]
    L += [f"    .{kind} " + ",".join(map(str, vals[i:i + 8])) for i in range(0, len(vals), 8)]
    return L


# The first line is blank: GNU as can misread an included file's first line.
L = ["",
     "| sfx_tables.inc - generated by tools/gen_sfx_tables.py. Do not edit.",
     "| The alternative send effects' curves (src/sendfx.inc).",
     "    .align 4"]
L += rows("sfx_rate", rate, "long")
L += rows("sfx_apc", ap, "word")
L += ["    .align 2"]
open(out, 'w').write("\n".join(L) + "\n")
print(f"wrote {out}")
